"""Build and check the knowledge bundle in docs/, an Open Knowledge Format (OKF) v0.2 bundle.

Usage:
    uv run python scripts/build_knowledge.py          # regenerate tables/, the validation SQL and every index.md
    uv run python scripts/build_knowledge.py --check  # conformance, links, staleness and generated-file drift

Generated here, never edited by hand:
  * docs/tables/**: one concept per dbt model, seed and source, from dbt/target/manifest.json and catalog.json.
    Run after `dbt docs generate` (scripts/run_pipeline.py does both). Edit descriptions in dbt/**/_*.yml.
  * powerbi/validation_queries.sql: the SQL of the Attested Computations in docs/computations/.
  * index.md files: entry titles and descriptions come from each concept's frontmatter. Outside docs/tables/
    the order and section headings are curated by hand and kept; new concepts are appended to the last
    section and deleted ones dropped.
Conventions for the bundle are in docs/conventions.md.
"""
